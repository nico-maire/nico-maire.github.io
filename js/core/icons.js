// Converts a bitmap into an SVG string. Rows are merged into horizontal runs to keep the markup small.
const cache = new Map();

export function pixelSvg(name) {
  if (cache.has(name)) return cache.get(name);
  const rows = ICONS[name] || ICONS.doc;
  let full = '';
  let dim = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 16) {
      const ch = row[x] || '.';
      if (ch === '.') { x++; continue; }
      let end = x + 1;
      while (end < 16 && row[end] === ch) end++;
      const seg = `M${x} ${y}h${end - x}v1h-${end - x}z`;
      if (ch === '#') full += seg; else dim += seg;
      x = end;
    }
  });
  const svg = `<svg viewBox="0 0 16 16" aria-hidden="true" focusable="false"><path d="${dim}" fill="currentColor" opacity=".38"/><path d="${full}" fill="currentColor"/></svg>`;
  cache.set(name, svg);
  return svg;
}
